// Run after every source/asset change. sw.js is generated; no network needed.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),version='2.0.3';
const files=JSON.parse(fs.readFileSync(path.join(__dirname,'offline-files.json'),'utf8'));
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const manifest=files.map(file=>{const bytes=fs.readFileSync(path.join(root,file));if(!bytes.length)throw Error('Empty asset: '+file);return {path:file,sha256:sha(bytes),bytes:bytes.length};});
if(new Set(files).size!==files.length)throw Error('Duplicate assets');
const release={version,id:sha(JSON.stringify(manifest)).slice(0,16),files:manifest};
const out='/* Generated by node tools/build-offline.cjs. */\nconst RELEASE='+JSON.stringify(release,null,2)+';\n'+fs.readFileSync(path.join(__dirname,'sw-template.js'),'utf8');
const target=path.join(root,'sw.js');
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==out)throw Error('Stale worker: run node tools/build-offline.cjs');}
else fs.writeFileSync(target,out);
console.log(`${version}: ${files.length} verified assets, ${manifest.reduce((n,f)=>n+f.bytes,0)} bytes, bundle ${release.id}`);
